@requires_inductor
def test_compile_false_reproduces_the_frozen_baseline_bit_exactly(corpus_tokens, fens,
                                                                 baseline_forward,
                                                                 capsys):
    """`compile=False` still IS the frozen baseline — raw bf16 words, every shape.

    THE ANCHOR OF THE WHOLE CHAIN. Gate 2' compares Inductor against the baseline
    artifact; that comparison only means anything if the baseline artifact is
    still reachable from this working tree. If this test fails, the eager path has
    drifted since the tag and every other number in this file is measuring the
    drift as well as the fusion.

    Compared on the WORDS rather than on the priors: a prior is a softmax over the
    ~30 legal columns of a 4096-wide row, so a logit the gather never reads could
    move without moving any prior.
    """
    evaluator = _build(False)
    lines = []
    try:
        assert evaluator.compiled is False
        for shape in evaluator.graph_sizes:
            want_policy = baseline_forward[f"policy_{shape}"]
            want_value = baseline_forward[f"value_{shape}"]
            rows = want_policy.shape[0]
            assert rows == (len(fens) // shape) * shape
            got_policy, got_value = _sweep(evaluator, corpus_tokens, shape, rows)
            bad_policy = int((got_policy != want_policy).sum())
            bad_value = int((got_value != want_value).sum())
            lines.append(f"  shape {shape:>3}: {rows:>4} positions, "
                         f"{bad_policy} of {want_policy.size:,} policy words differ, "
                         f"{bad_value} values")
            assert bad_policy == 0, (
                f"compile=False no longer reproduces tag GUOFISH_NUMERICS_BASELINE "
                f"at shape {shape}: {bad_policy} of {want_policy.size} bf16 policy "
                f"words differ. The eager path has drifted since the tag, so the "
                f"baseline every other test here compares against is stale.")
            assert bad_value == 0, (
                f"{bad_value} values differ from the frozen baseline at shape {shape}")
    finally:
        evaluator.close()
    with capsys.disabled():
        print("\nC12b — compile=False against the frozen eager baseline")
        print("\n".join(lines))


