@requires_inductor
def test_autotuning_is_off_because_that_is_what_pins_the_kernels(inductor):
    """The brief asks the autotune cache to be pinned. C12b removes it instead.

    Left on, Inductor benchmarks several Triton configs per pointwise/reduction
    kernel at first call and caches the winner in a `.best_config` file. The
    winner comes from measured times, so it varies with GPU clock and machine
    load: **17 of 28 `.best_config` files differ between two cold compiles of this
    model**, and a reduction kernel's block size changes the accumulation order,
    which changes the bits.

    Turned off, the heuristics emit one config per kernel and ZERO `.best_config`
    files are written — so there is no cache to pin, nothing keyed on the GPU,
    driver or torch version, and nothing to go stale. It is asserted here rather
    than only recorded in DECISIONS.md because it is the mechanism the two
    determinism tests below depend on, and a future torch that changes the
    default would otherwise break them with no explanation attached.
    """
    import torch._inductor.config as inductor_config

    assert inductor.graph.inductor_settings == {
        "use_static_cuda_launcher": False, "triton.autotune_pointwise": False}
    assert inductor_config.triton.autotune_pointwise is False
    # Not a preference: with torch 2.8.0+cu129 / triton 3.4.0 on this device the
    # static launcher raises OverflowError on the first Inductor kernel.
    assert inductor_config.use_static_cuda_launcher is False


@requires_inductor
def test_a_second_capture_in_this_process_agrees_bit_for_bit(inductor, corpus_tokens,
                                                             fens):
    """Same code, same GPU, same driver — twice — must be the same bits.

    A fresh `TorchEvaluator` re-runs warmup and re-captures every shape, so this
    exercises the capture path rather than replaying the graphs already built.
    It is the weaker of the two determinism checks, because both captures share
    one interpreter's compile cache and loaded Triton binaries; the subprocess
    test below is the one that closes that.
    """
    shape = FORWARD_MAX_BATCH
    rows = (len(fens) // shape) * shape
    first, first_value = _sweep(inductor, corpus_tokens, shape, rows)
    second_evaluator = _build(True)
    try:
        second, second_value = _sweep(second_evaluator, corpus_tokens, shape, rows)
    finally:
        second_evaluator.close()
    assert np.array_equal(first, second), (
        f"two captures in one process disagree on "
        f"{int((first != second).sum())} of {first.size} policy words")
    assert np.array_equal(first_value, second_value)


@requires_inductor
def test_a_fresh_process_reproduces_the_priors_bit_for_bit(inductor, corpus_tokens,
                                                           fens, capsys):
    """The determinism criterion as the brief states it: across RUNS.

    A run is a process. Two captures in one interpreter share the compile cache,
    the loaded Triton binaries, the cuBLAS handles and the allocator's arenas, so
    agreeing with itself is a much weaker claim than agreeing with a process that
    started cold — and it is the weaker claim an in-test loop would be making.

    SPSA tuning is next, and a nondeterministic engine makes every subsequent
    measurement noisier; the brief says stop and report rather than ship one.
    """
    completed = subprocess.run(
        [sys.executable, str(DIGEST_TOOL), "--compile",
         "--max-batch", str(FORWARD_MAX_BATCH)],
        capture_output=True, text=True, cwd=str(REPO_ROOT))
    assert completed.returncode == 0, (
        f"the digest tool failed:\n{completed.stdout[-2000:]}\n{completed.stderr[-2000:]}")
    marker = "C12B_FORWARD_DIGEST "
    payloads = [line for line in completed.stdout.splitlines() if line.startswith(marker)]
    assert payloads, f"no digest in the tool's output:\n{completed.stdout[-2000:]}"
    fresh = json.loads(payloads[-1][len(marker):])
    assert fresh["compile"] is True

    lines = []
    for shape in inductor.graph_sizes:
        rows = (len(fens) // shape) * shape
        policy, value = _sweep(inductor, corpus_tokens, shape, rows)
        here = hashlib.sha256(policy.tobytes()).hexdigest()
        there = fresh["shapes"][str(shape)]["policy_sha256"]
        lines.append(f"  shape {shape:>3}: {here[:24]} vs {there[:24]}  "
                     f"{'same' if here == there else 'DIFFER'}")
        assert here == there, (
            f"a fresh process produced different priors at shape {shape}.\n"
            f"  this process : {here}\n  fresh process: {there}\n"
            f"Determinism is the property most at risk in this chunk and the one "
            f"worth most; the brief says stop and report rather than ship without it.")
        assert hashlib.sha256(value.tobytes()).hexdigest() == \
            fresh["shapes"][str(shape)]["value_sha256"]
    with capsys.disabled():
        print("\nC12b determinism — policy digests, this process vs a fresh one")
        print("\n".join(lines))
        print(f"  fresh process ran on {fresh['provenance']['cuda_device']}, "
              f"torch {fresh['provenance']['torch']}")


