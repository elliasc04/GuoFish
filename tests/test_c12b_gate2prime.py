@requires_inductor
def test_the_prior_shift_is_reported(inductor_priors, baseline_forward, fens, capsys):
    """How far Inductor moved the priors. REPORTED — this is not a bound.

    The brief is explicit that Gate 2' is a much looser gate than Gate 2 was and
    that saying so is part of passing it. Gate 2's bound was 1e-6; what is printed
    here is three orders larger, and that is the intended consequence of fusing
    the epilogues, not a defect.

    What IS asserted is only that the comparison is coherent: the priors are
    finite and still sum to 1 per position. A NaN or a broken softmax would
    otherwise sail through a test whose headline number is "reported".
    """
    got, offsets = inductor_priors
    want = baseline_forward["priors"]
    want_offsets = baseline_forward["move_offset"]
    assert np.array_equal(offsets, want_offsets), (
        "the two engines gathered different move lists; the priors are not "
        "element-wise comparable and every number below would be meaningless")

    deltas = np.abs(got.astype(np.float64) - want.astype(np.float64))

    # THE ARM UNDER TEST IS ACTUALLY THE FUSED ONE. Everything else in this file
    # would pass if `compile=True` silently produced the eager forward: the
    # capture-fidelity comparison would be eager-against-eager, the determinism
    # checks would agree trivially, and Gate 2' would report 100% move agreement
    # against a baseline it had merely reproduced. That is the self-comparison
    # trap the brief calls the worst available outcome, and this is the assertion
    # that makes it impossible — a genuinely fused forward moves ~60% of the bf16
    # policy words, so bit-identical priors here mean Inductor never ran.
    assert deltas.max() > 0.0, (
        "the Inductor arm's priors are bit-identical to the frozen EAGER "
        "baseline's at every one of the corpus's priors. Inductor is not running, "
        "so Gate 2' is comparing the baseline against itself and every result in "
        "this file is vacuous.")

    per_position_linf, per_position_l1 = [], []
    for i in range(len(fens)):
        begin, end = int(offsets[i]), int(offsets[i + 1])
        block = deltas[begin:end]
        per_position_linf.append(float(block.max()) if block.size else 0.0)
        per_position_l1.append(float(block.sum()))
        total = float(got[begin:end].sum())
        assert np.isfinite(total) and abs(total - 1.0) < 1e-4, (
            f"the Inductor priors at {fens[i]} sum to {total}, not 1")

    linf = np.array(per_position_linf)
    l1 = np.array(per_position_l1)
    with capsys.disabled():
        print("\nC12b — Gate 2' prior shift, Inductor against the frozen eager baseline")
        print(f"  {deltas.size:,} priors over {len(fens)} positions; "
              f"{int((deltas == 0).sum()):,} bit-identical "
              f"({100 * (deltas == 0).mean():.1f}%)")
        print(f"  |dprior| overall : max {deltas.max():.3e}  "
              f"p99 {np.percentile(deltas, 99):.3e}  "
              f"median {np.median(deltas):.3e}")
        print(f"  per-position Linf: max {linf.max():.3e}  "
              f"p99 {np.percentile(linf, 99):.3e}  median {np.median(linf):.3e}  "
              f"min {linf.min():.3e}")
        print(f"  per-position L1  : max {l1.max():.3e}  "
              f"p99 {np.percentile(l1, 99):.3e}  median {np.median(l1):.3e}")
        print(f"  for scale, Gate 2's bound was 1e-06 and this is "
              f"{deltas.max() / 1e-6:,.0f}x it — by design, not by defect")


@requires_inductor
def test_the_inversion_rate_is_reported(inductor_priors, baseline_forward, fens, capsys):
    """Prior-ordering inversions: measured, with the margin distribution. Not gated.

    Gate 2 gated inversions at zero because PUCT reads priors only through
    comparisons, so a reversed pair changes which child is selected. That bound
    cannot survive a ~1e-3 shift: the minimum inter-prior gap on this corpus is
    1.927e-06 (C10b), so near-ties invert freely — and a swap between priors that
    close was arbitrary before the change too.

    The one thing asserted is a COHERENCE check, not a bound on the engine: if
    every prior moved by at most `delta`, then a pair can only swap order if its
    baseline gap was at most `2 * delta`. An inversion at a wider gap would mean
    the two arrays are not the same 520 positions in the same order, which is a
    bug in this test rather than a finding about Inductor.
    """
    got, offsets = inductor_priors
    want = baseline_forward["priors"]
    delta = float(np.abs(got.astype(np.float64) - want.astype(np.float64)).max())
    reachable = 2 * delta

    inversions = 0
    pairs = 0
    gaps = []
    worst = None
    for i in range(len(fens)):
        begin, end = int(offsets[i]), int(offsets[i + 1])
        ref = want[begin:end].astype(np.float64)
        new = got[begin:end].astype(np.float64)
        if ref.size < 2:
            continue
        sign_ref = np.sign(ref[:, None] - ref[None, :])
        sign_new = np.sign(new[:, None] - new[None, :])
        inverted = np.triu(sign_ref * sign_new, 1) < 0
        pairs += ref.size * (ref.size - 1) // 2
        count = int(inverted.sum())
        if count:
            inversions += count
            gap = np.abs(ref[:, None] - ref[None, :])[inverted]
            gaps.append(gap)
            if worst is None or gap.max() > worst[1]:
                worst = (fens[i], float(gap.max()))

    gap_all = np.concatenate(gaps) if gaps else np.zeros(0)
    with capsys.disabled():
        print("\nC12b — Gate 2' prior-ordering inversions (measured, not gated)")
        print(f"  {inversions:,} inverted pairs of {pairs:,} comparable "
              f"({100 * inversions / max(1, pairs):.3f}%)")
        if gap_all.size:
            print(f"  baseline gap at an inverted pair: max {gap_all.max():.3e}  "
                  f"p99 {np.percentile(gap_all, 99):.3e}  "
                  f"median {np.median(gap_all):.3e}  min {gap_all.min():.3e}")
            print(f"  widest: {worst[1]:.3e} at {worst[0]}")
        print(f"  max |dprior| is {delta:.3e}, so no pair wider than "
              f"{reachable:.3e} can invert")

    if gap_all.size:
        assert gap_all.max() <= reachable * 1.000001, (
            f"an inverted pair had a baseline gap of {gap_all.max():.6e}, wider "
            f"than 2 x max|dprior| = {reachable:.6e} could cross. The two prior "
            f"arrays are not the same positions in the same order.")


