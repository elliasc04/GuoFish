@requires_inductor
def test_the_manual_capture_did_not_change_the_inductor_forward(inductor, corpus_tokens,
                                                                capsys):
    """Capture is a no-op on the numerics; fusion is not. This separates them.

    The brief's hazard 1 is that Inductor and the manual capture will fight if
    they are allowed to — `mode="reduce-overhead"` brings compile-owned cudagraph
    trees, which would orphan every C10b shape and staleness drill. C12b ships
    default mode captured by the existing machinery instead, and this is the
    evidence the combination is sound: captured replay against the un-captured
    compiled call, at every shape, zero differing words.

    If this ever fails, the agreement rate below is not interpretable whatever it
    prints, because the two arms would then be different forwards for a second,
    unintended reason.
    """
    import torch

    graph = inductor.graph
    lines = []
    for shape in graph.sizes:
        rows = (len(corpus_tokens) // shape) * shape
        bad = 0
        for start in range(0, rows, shape):
            got, _ = _sweep(inductor, corpus_tokens[start:start + shape], shape, shape)
            want, _ = graph.eager(shape)
            torch.cuda.synchronize()
            bad += int((got != want.view(torch.uint16).cpu().numpy()).sum())
        lines.append(f"  shape {shape:>3}: {bad} differing policy words over "
                     f"{rows} positions")
        assert bad == 0, (
            f"the captured Inductor graph disagrees with the un-captured compiled "
            f"call at shape {shape} ({bad} words). That is a CAPTURE defect, not "
            f"the fusion re-baselining this chunk is about.")
    with capsys.disabled():
        print("\nC12b capture fidelity (captured replay vs un-captured compiled call)")
        print("\n".join(lines))


@requires_inductor
def test_warmup_converged_before_anything_was_captured(inductor):
    """Brief hazard 2: a recompilation during capture would be silent and fatal.

    `_warm_to_convergence` runs whole warmup rounds until a round adds no dynamo
    frame, so two rounds is the floor — the first compiles, the second confirms.
    Fewer than two would mean the convergence check never actually ran; the frame
    delta equalling the shape count is the other half, and says each shape
    compiled exactly one frame rather than one shape compiling several.
    """
    graph = inductor.graph
    assert set(graph.warmup_rounds) == set(graph.sizes)
    for shape, rounds in graph.warmup_rounds.items():
        assert rounds >= 2, (
            f"shape {shape} converged in {rounds} round(s); the confirming round "
            f"never ran, so convergence was assumed rather than observed")

    # THE RECOMPILE LIMIT, WHICH IS A SHIPPED-CONFIG BUG THIS CHUNK FOUND.
    # `torch._dynamo`'s default is 8; the shipping ladder is nine shapes and
    # `dynamic=False` makes each one its own frame, so the ninth blew the limit
    # and dynamo silently ran shape 128 EAGER — the engine's `max_batch`. It was
    # visible only as a throughput row measuring exactly 1.000x with 0 of 524,288
    # policy words differing.
    assert graph.recompile_limit >= len(graph.sizes), (
        f"dynamo's recompile limit is {graph.recompile_limit} for "
        f"{len(graph.sizes)} captured shapes; the largest shapes will fall back "
        f"to eager instead of compiling")

    # And the property the limit exists to protect, asked of every shape directly
    # rather than inferred from a counter. Counting compiled frames cannot answer
    # this: a shape that hit the limit stops compiling and so converges
    # immediately, and a second `torch.compile` of the same module in one process
    # reuses dynamo's cache and legitimately compiles nothing.
    graph.assert_every_shape_is_fused()


@requires_inductor
def test_no_dynamo_frame_is_compiled_after_warmup(inductor, corpus_tokens):
    """Acceptance 4, driven through the production callback at every width.

    Not only at the captured shapes: `pad_to` means a batch of 21 runs at shape
    24, so every count in [1, max_batch] is a width the dispatcher can hand over
    and none of them may reach the compiler. A recompilation mid-search is a
    multi-second stall that reads as a hung engine — and inside a capture it is
    worse than a stall.
    """
    from playing.v6.graphs import dynamo_frame_count

    before = dynamo_frame_count()
    for count in range(1, inductor.max_batch + 1):
        inductor._input_np[:count] = corpus_tokens[:count]
        inductor._evaluate(count)
    assert dynamo_frame_count() == before, (
        f"driving counts 1..{inductor.max_batch} through the callback compiled "
        f"{dynamo_frame_count() - before} dynamo frame(s)")
    inductor.assert_no_recompilation("after sweeping every dispatchable width")


