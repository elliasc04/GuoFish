# --- availability, resolved once and reported per test (Amendment D) --------

def _why_unavailable() -> str | None:
    """The reason Gate 2' cannot run here, or None.

    A guarded import plus a skipif marker, never a module-scope `importorskip` —
    the C7 incident was a module-scope skip silently taking 242 tests out of the
    Linux run while Global Rule 3 reported a pass.
    """
    try:
        import torch
    except Exception as exc:  # noqa: BLE001
        return f"torch is not importable ({type(exc).__name__}: {exc})"
    if not torch.cuda.is_available():
        return ("no CUDA device; Inductor emits Triton and the manual capture has "
                "no CPU equivalent, so this arm certifies nothing without a GPU")
    if not MODEL.exists():
        return f"the v5 checkpoint is missing ({MODEL})"
    for spec in (FORWARD, SEARCH, MANIFEST):
        if not _path(spec).exists():
            return (f"missing baseline artifact {_path(spec)}; generate it with "
                    f"python tools/gen_c12b_baseline.py")
    return None


