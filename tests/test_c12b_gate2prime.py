"""C12b — Gate 2', the numerics gate re-based onto the frozen eager C++ engine.

WHAT REPLACED WHAT, AND WHY THAT IS NOT A LOOSENING
===================================================
Gate 2 asked whether the C++ gather reproduced ATen's priors to 1e-6 with no
ordering inversions. Inductor fuses bias/GELU/LayerNorm into the matmul epilogue.
It changes NO precision — the forward is bf16 before and after — but it changes
the ACCUMULATION ORDER, and a bf16 logit moved by one ulp moves a prior by ~1e-3,
three orders over that bound. So Gate 2 cannot be re-run against Python after
Inductor: it would fail, for a known and intended reason, and a gate that fails
for an intended reason teaches nothing.

The certification chain the C12b brief writes down instead:

    Python reference ──Gate 1 (bit-exact, replay)───► C++ tree logic
                     ──Gate 2 (<=1e-6, 0 inversions)► C++ eager forward
                     ──Gate 2b (497/500 = 99.4%)────► C++ eager engine
                                                            │
                                                       Gate 2' (HERE)
                                                            ▼
                                                       C++ Inductor engine

**Gate 1 is untouched and stays Python-anchored forever.** It runs the replay
evaluator with no network in the loop, so no forward change can reach it; Rule
2's golden data is network-free and nothing in this chunk affects it. That is the
fact that makes the move safe rather than a loosening. **Gate 2 and Gate 2b are
frozen as historical certifications and are not re-run** — C10's 497/500 stands
as the record that the C++ engine matches Python.

What this file compares against is `baseline/`, generated by
`tools/gen_c12b_baseline.py` from the eager engine at tag
GUOFISH_NUMERICS_BASELINE. That is C++ and torch output, so it is NOT golden data
and deliberately does not live in `golden/` (Global Rule 2).

THIS IS A MUCH LOOSER GATE THAN GATE 2 WAS, AND SAYING SO IS PART OF PASSING IT
==============================================================================
(And looser again than the C12b brief first drafted it — see `MIN_AGREEMENT`.)
A ~1e-3 prior perturbation is far larger than 1e-6. The honest claim this file
supports is **"the engine plays the same moves"**, not "the engine computes the
same numbers" — and the second is simply false, by design, which
`test_the_prior_shift_is_reported` prints in full rather than hides. Gate 5 is
what prices the difference in ELO.

**Inversions are measured, not gated.** The minimum inter-prior gap on this
corpus is 1.927e-06 (C10b), so a ~1e-3 shift inverts near-ties freely; a swap
between priors that close was arbitrary before the change too. What IS asserted
is that no inversion happens at a gap the measured shift could not have crossed,
which is a coherence check on the measurement rather than a bound on the engine.

WHAT IS ACTUALLY GATED HERE
===========================
  1. `compile=False` reproduces the frozen baseline BIT-EXACTLY, at every
     captured shape, on the raw bf16 words. The fallback is real or the whole
     chain has no anchor.
  2. Capture did not change the Inductor forward — captured replay against the
     un-captured compiled call, zero differing words.
  3. No dynamo frame is compiled after warmup, per captured shape.
  4. Priors are bit-identical across repeated runs, INCLUDING a fresh process.
  5. **>= 98%** move agreement against the frozen baseline.

The 98% is a ruled figure, not the brief's original 99%, and the near-tie
criterion the brief paired with it is now REPORTED rather than gated. Both moves
are the owner's, taken on evidence the harness cannot produce: the decisive
disagreements were adjudicated by hand against Stockfish at high depth and every
Inductor move came back equal or better. `MIN_AGREEMENT` carries the full
provenance, and `test_the_decisive_disagreements_are_listed_for_adjudication`
prints the list the next adjudication would work from. Nothing here was relaxed
to make a red suite green — the measurement is unchanged and is still printed in
full; what changed is which threshold the project decided it wanted.

Per Amendment D there are no module-scope skips. Every test is individually
marked and the reason names which of torch / CUDA / the checkpoint / the baseline
is missing, so a skipped platform reports a count and a reason rather than a
silent pass. **The Linux arm has no CUDA and certifies nothing in this file** —
C12's Amendment D note applies unchanged, and a green Linux run here means every
test skipped, not that Inductor was checked.
"""

