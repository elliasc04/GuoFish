def _sweep(evaluator, tokens, shape, rows):
    """`rows` positions through the PRODUCTION callback at exactly `shape`.

    Through `_evaluate` rather than around it, and in full blocks only, so no row
    is padding and every word compared is a word a real batch would have
    produced. This is the same blocking `tools/gen_c12b_baseline.py` recorded the
    baseline with; comparing a different blocking would measure the shape term
    (cuBLAS tiling) rather than the fusion term.
    """
    policy = np.zeros((rows, guofish_core.POLICY_SIZE), dtype=np.uint16)
    value = np.zeros(rows, dtype=np.float32)
    for start in range(0, rows, shape):
        evaluator._input_np[:shape] = tokens[start:start + shape]
        evaluator._evaluate(shape)
        policy[start:start + shape] = evaluator._policy_np[:shape]
        value[start:start + shape] = evaluator._value_np[:shape]
    return policy, value


@pytest.fixture(scope="module")
def inductor_priors(inductor, corpus_tokens, fens):
    """The production gather over logits INDUCTOR produced, at shape 1.

    Shape 1 because that is what the W=1/K=1 search below evaluates every batch
    at, so these are the priors Gate 2''s own move comparison actually saw.
    `guofish_core.gather_softmax` is the function the dispatcher calls, so this is
    the shipping path end to end: replay -> bf16 policy buffer -> the C++ gather.
    """
    policy, _ = _sweep(inductor, corpus_tokens, 1, len(fens))
    offsets = [0]
    rows = []
    for index, fen in enumerate(fens):
        uci, row = guofish_core.gather_softmax(fen, policy[index])
        rows.append(row)
        offsets.append(offsets[-1] + len(uci))
    return np.concatenate(rows).astype(np.float32), np.array(offsets, dtype=np.uint64)


