def test_part1_the_floor_is_the_larger_of_the_count_and_the_fraction():
    """`ANALYSIS.md` §3: "express it as a fraction, not a count".

    25,000 is 42% of a 60,000 allocation and 6% of a 400,000 one, and once the
    budget varies only one of those is the floor anyone meant.
    """
    tm = TimeManager()
    c = DEFAULT_CONSTANTS
    assert tm.floor_for(60_000, n_legal=30) == c.floor_absolute
    assert tm.floor_for(800_000, n_legal=30) == int(c.floor_fraction * 800_000)
    assert tm.floor_for(200_000, n_legal=30) == c.floor_absolute, (
        "FLOOR_FRACTION is chosen so the two coincide at the deployed budget")


def test_part1_a_forcing_move_bypasses_the_floor():
    """`n_legal <= 2` is provably safe and free, per the brief.

    With one legal reply the single visited child is trivially unreachable and
    the exit fires at once; with two there is nothing a floor is protecting.
    Recaptures are deliberately NOT in this set — `n_lock` for that subset is
    computable from Arm B and is out of v1.
    """
    tm = TimeManager()
    assert tm.floor_for(200_000, n_legal=1) == 0
    assert tm.floor_for(200_000, n_legal=2) == 0
    assert tm.floor_for(200_000, n_legal=3) == DEFAULT_CONSTANTS.floor_absolute


def _plan_at(target_nodes: int, current: int = 0) -> TMPlan:
    plan = TMPlan()
    plan.applicable = True
    plan.target_nodes = target_nodes
    plan.target_total = max(current, target_nodes)
    plan.floor_at = 25_000
    return plan


def test_part1_at_floor_counts_competitors_at_theta_over_the_top_four():
    """`n_competing = |{c in top4 : visits(c) >= theta * visits(leader)}|`.

    TOP FOUR AND NO MORE, because that is the statistic F3 was fitted on:
    `move_stats` records `top4` and `n_competing` saturates at 4 there. Reading
    a fifth child here would apply a multiplier fitted on a different quantity.
    """
    tm = TimeManager()
    plan = _plan_at(200_000)
    children = [("a", 1000), ("b", 600), ("c", 490), ("d", 100), ("e", 900)]
    tm.at_floor(plan, children, delivered=25_000, current_root_visits=25_000)
    # Sorted first: 1000, 900, 600, 490 are the top four; theta=0.5 keeps
    # 1000, 900 and 600.
    assert plan.n_competing == 3


def test_part1_at_floor_exits_when_one_competitor_is_provably_alone():
    """Branch one of three, and the one Arm B prices at 22.3% of moves.

    The criterion is `ANALYSIS.md`'s: the leader's visit margin already exceeds
    every simulation the target has left, so no redistribution of the remainder
    can change the argmax. Measured over 5,172 laddered moves, the argmax
    changes on 0 of the moves where it fires.
    """
    tm = TimeManager()
    plan = _plan_at(30_000, current=28_000)
    decision = tm.at_floor(plan, [("a", 20_000), ("b", 100)],
                           delivered=25_000, current_root_visits=28_000)
    assert decision.exit_now
    assert decision.n_competing == 1 and decision.leader_unreachable
    assert plan.would_have_exited_at == 25_000


def test_part1_at_floor_does_not_exit_when_the_runner_up_can_still_catch_up():
    tm = TimeManager()
    plan = _plan_at(200_000, current=25_000)
    decision = tm.at_floor(plan, [("a", 13_000), ("b", 11_000)],
                           delivered=25_000, current_root_visits=25_000)
    assert not decision.exit_now
    assert not decision.leader_unreachable


