@requires_wrapper
def test_part1_the_floor_survives_the_handoff_into_allot():
    """THE GUARDRAIL, AS A TEST. `_tm_movestogo` must return the FLOORED
    `moves_left` -- `TimeManager.moves_left`'s `max(FLOOR, fitted)` -- not the
    raw estimator output. This is the whole reason `2mLvILE3` (193 of our
    moves, ply 385) didn't flag: at that ply the unfloored curve says ~1.6
    moves remain, which would have made `_allot` divide by 1.6 and hand back
    most of a 23-second clock in one move.
    """
    from playing.v6.playv6 import EngineConfig
    uci, module = _uci_for_plan(EngineConfig(time_manager=True))
    params = module.GoParams(["wtime", "23000", "btime", "23000", "winc", "3000"])
    # `tm.plan` takes `ply` directly -- no need to walk a real board through
    # 400 plies (and a deterministic "always the first legal move" walk hits
    # an automatic draw by repetition long before it gets there anyway).
    plan = uci.tm.plan(clock_ms=23_000.0, increment_ms=3_000, ply=400,
                       piece_count=8, current_root_visits=0, n_legal=20)
    assert plan.moves_left_floored, "the premise: this ply must floor"
    assert plan.moves_left == float(DEFAULT_CONSTANTS.moves_left_floor)
    mo = uci._tm_movestogo(plan)
    assert mo == float(DEFAULT_CONSTANTS.moves_left_floor)
    # And `_allot` with it does not collapse to a near-zero divisor: dividing a
    # 23 s clock by 23 rather than by 1.6 is the whole point.
    allotted = uci._allot(params, movestogo_override=mo)
    naive = uci._allot(params, movestogo_override=1.6)
    assert allotted < naive, "flooring must ask for LESS than the raw estimate"


