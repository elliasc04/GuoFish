@requires_fit
def test_part0_the_module_constants_match_the_fit_that_produced_them():
    """The one way a hard-coded constants table can rot.

    `time_manager.py` carries the numbers rather than reading the JSON, because
    an engine that needs a file on disk to plan a move has a new way to fail on
    move one. The cost of that choice is exactly this test: if someone refits
    and does not update the module, or edits the module and does not refit, the
    two disagree here rather than in a rated game.
    """
    fit = json.loads(CONSTANTS_JSON.read_text(encoding="utf-8"))
    c = DEFAULT_CONSTANTS

    assert c.a == fit["moves_left"]["A"]
    assert c.tau == fit["moves_left"]["tau"]
    assert c.s == pytest.approx(fit["moves_left"]["s"], abs=1e-4)
    assert c.moves_left_floor == fit["moves_left"]["floor_our_moves"]

    assert c.nps_global == pytest.approx(fit["nps"]["global_median"], abs=1.0)
    assert c.nps_alpha == fit["nps"]["alpha"]
    fitted_buckets = [(b["lo"], b["hi"], float(b["median"]))
                      for b in fit["nps"]["buckets"]]
    assert list(c.nps_buckets) == fitted_buckets

    assert c.theta == fit["complexity"]["theta"]
    assert {str(k): v for k, v in MULTIPLIERS.items()} == \
        fit["complexity"]["multipliers"]


@requires_fit
def test_part0_the_multiplier_set_is_mean_neutral_over_the_measured_frequencies():
    """`ANALYSIS.md` §4a's constraint, as a test rather than as a footnote.

    "If `E[multiplier] != 1` the result is a systematic over- or under-spender
    wearing an adaptive costume." The frequencies are F3's, over the 5,172 Arm B
    moves that reached the 25,000 rung.

    THIS IS WHY `m(1)` IS 0.92 AND NOT THE BRIEF'S 1.0. With the common case
    pinned at 1.0 and every other rung above it, `E[m]` is 1.08 by construction
    and this test cannot pass. Rescaling the hand set by its own mean keeps the
    measured ordering — which is the half the data supports — and moves only the
    level, which was chosen by hand anyway.
    """
    fit = json.loads(CONSTANTS_JSON.read_text(encoding="utf-8"))
    table = fit["complexity"]["table"]
    total = sum(row["moves"] for row in table)
    expected = sum(row["moves"] / total * MULTIPLIERS[row["n_competing"]]
                   for row in table)
    assert expected == pytest.approx(1.0, abs=0.01), (
        f"E[m] = {expected:.4f}. A multiplier set whose mean is not 1.0 spends "
        f"{(expected - 1) * 100:+.1f}% more than the base curve on every move, "
        f"which is a level change dressed as an adaptive one.")


@requires_fit
def test_part0_the_measured_ordering_survives_into_the_shipped_multipliers():
    """The magnitudes are hand-chosen; the ORDERING is not, and it is measured.

    P(argmax at 25k differs from final) is monotone in `n_competing` over 5,172
    moves. A multiplier set that did not respect that ordering would be
    spending more on the positions the data says are easier.
    """
    fit = json.loads(CONSTANTS_JSON.read_text(encoding="utf-8"))
    table = sorted(fit["complexity"]["table"], key=lambda r: r["n_competing"])
    rates = [row["p_changed"] for row in table]
    assert rates == sorted(rates), "the measured table is not monotone any more"
    ms = [MULTIPLIERS[row["n_competing"]] for row in table]
    assert ms == sorted(ms), "the multipliers do not follow the measured order"


def test_part0_the_nps_buckets_partition_every_reachable_piece_count():
    """A position with 3 pieces and one with 32 must both land somewhere.

    The endgame bucket is `<= 10` rather than the brief's `10-7 / <= 6` split,
    which is the occupancy adjustment the brief itself asks for — the `<= 6`
    cell holds 28 of L0's 1,805 searches, under the ~100 bar.
    """
    c = DEFAULT_CONSTANTS
    for pieces in range(2, 33):
        assert c.bucket(pieces) is not None, pieces
    assert c.bucket(None) is None
    los = [lo for lo, _, _ in NPS_BUCKETS]
    his = [hi for _, hi, _ in NPS_BUCKETS]
    assert min(los) == 0 and max(his) == 32, "the buckets leave a gap"


def test_part0_nps_rises_monotonically_as_pieces_come_off():
    """F2's headline, pinned. If a refit inverts it, the bucketing is wrong."""
    medians = [med for _, _, med in NPS_BUCKETS]
    assert medians == sorted(medians), medians
    assert medians[-1] / medians[0] > 1.5, (
        "the endgame regime is the whole reason F2 buckets at all; a spread "
        "under 1.5x would not justify the extra state")


