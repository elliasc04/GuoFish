def test_part1_moves_left_is_the_fitted_exponential_in_our_moves():
    tm = TimeManager()
    c = DEFAULT_CONSTANTS
    ours, floored = tm.moves_left(0)
    assert ours == pytest.approx(c.s * c.a / 2.0, rel=1e-9)
    assert not floored
    # Halved because we move on every other ply, and that is the only
    # conversion between the fit's units and the law's.
    assert ours == pytest.approx(48.1, abs=0.2)


def test_part1_moves_left_never_falls_below_the_floor():
    """MOVES_LEFT.md's inspection paradox, as the guard the brief demands.

    `E[remaining | alive]` bottoms out at ply 86 and RISES; the exponential
    keeps falling. Past that point an unfloored estimator is optimistic exactly
    where the clock is thinnest, which is `4YCsGtQ8`'s mechanism from the other
    direction.
    """
    tm = TimeManager()
    floor = DEFAULT_CONSTANTS.moves_left_floor
    for ply in range(0, 400, 7):
        ours, floored = tm.moves_left(ply)
        assert ours >= floor, ply
        assert floored == (ours == float(floor))
    assert tm.moves_left(400)[0] == float(floor)


def test_part1_moves_left_is_non_increasing_up_to_the_floor():
    tm = TimeManager()
    values = [tm.moves_left(p)[0] for p in range(0, 200)]
    assert all(b <= a + 1e-9 for a, b in zip(values, values[1:]))


def test_part1_the_worked_check_from_the_brief_is_reproduced():
    """`4YCsGtQ8` at our move 60 — ply 120 — with a truth of 25 of our moves.

    The unfloored estimator says about 17 and over-allocates by 1.5x, and the
    over-allocation compounds every move after it. The floor holds it at 23,
    which UNDER-shoots the truth slightly. That asymmetry is the whole design:
    the floor is wrong in the direction that costs search, not the one that
    costs games.
    """
    tm = TimeManager()
    c = DEFAULT_CONSTANTS
    unfloored = c.s * c.a * math.exp(-120 / c.tau) / 2.0
    ours, floored = tm.moves_left(120)
    assert unfloored < 18.0
    assert floored and ours == float(c.moves_left_floor)
    assert ours < 25, "the floored estimator must still under-shoot the truth"
    assert 25 / unfloored > 1.4, "the unfloored one over-allocates by ~1.5x"


def test_part1_base_time_holds_back_the_reserve_and_the_emergency():
    """`(clock - reserve - emergency) / moves_left + increment`, term by term."""
    tm = TimeManager()
    c = DEFAULT_CONSTANTS
    plan = tm.plan(clock_ms=600_000, increment_ms=3_000, ply=0, piece_count=32,
                   current_root_visits=0, n_legal=20)
    expected_ml = c.s * c.a / 2.0
    expected = (600_000 - c.reserve_ms - c.emergency_ms) / expected_ml + 3_000
    assert plan.base_time_ms == pytest.approx(expected, rel=1e-9)
    assert plan.applicable and not plan.clamped_by_clock


def test_part1_the_emergency_is_what_keeps_the_estimator_off_zero():
    """Spending `time_left/moves_left + inc` for `moves_left` moves lands on 0.

    Asserted as the difference the constant makes rather than as its value: with
    the emergency removed the plan is strictly larger, and the gap is the
    emergency amortised over the remaining moves.
    """
    tm = TimeManager()
    no_emergency = TimeManager(TMConstants(emergency_ms=0.0))
    kwargs = dict(clock_ms=60_000, increment_ms=3_000, ply=40, piece_count=20,
                  current_root_visits=0, n_legal=30)
    with_e = tm.plan(**kwargs).base_time_ms
    without_e = no_emergency.plan(**kwargs).base_time_ms
    assert without_e > with_e
    ml = tm.moves_left(40)[0]
    assert without_e - with_e == pytest.approx(
        DEFAULT_CONSTANTS.emergency_ms / ml, rel=1e-9)


