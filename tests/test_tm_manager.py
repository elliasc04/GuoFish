"""TM — the time manager. Parts 0, 1, 2 and 3.

The brief is `docs/TC/tc_manager_brief.md`; the constants it is written against
are `docs/TC/TM_CONSTANTS.md`, regenerated by
`telemetry/fit_tm_constants.py` from data already on disk.

WHAT EACH PART HAS TO PROVE HERE, AND WHAT IT CANNOT
====================================================

  Part 0  the constants the engine carries are the constants that were fitted.
          A module that drifts from its own fit is the failure this file's
          first section exists to catch, and it is checked against the JSON the
          fit writes rather than against a number retyped here.

          MEAN-NEUTRALITY IS ASSERTED, NOT ASSUMED. `ANALYSIS.md` §4a asks for
          `E[m]` to be reported next to any proposed multiplier set; here it is
          a test, computed over the frequencies F3 measured.

  Part 1  the control law, which is pure arithmetic and therefore fully
          testable: the estimator and its floor, the reserve, the emergency,
          the 40% clamp, the per-bucket nps smoother, and the one evaluation at
          the smart-pruning floor with its three outcomes.

          What is NOT here: whether the allocation is any good. That is
          `telemetry/tm_replay.py` over eighty recorded games, and after it the
          shadow week.

  Part 2  the four rows of the switch table, at the planner level. Off means
          the planner returns what it returned before, which is asserted by
          calling it both ways on the same inputs rather than by remembering
          what it used to say.

  Part 3  shadow mode is computed and ignored — the hook returns None on every
          call with the switch off — and the record carries the eight fields
          the brief names.

AMENDMENT D: no module-scope skip. `playing.v6.time_manager` imports only the
standard library, so the Part 0/1 tests always run; the wrapper tests carry
their own marker.
"""
