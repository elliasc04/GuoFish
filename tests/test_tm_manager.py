def test_search_move_takes_a_budget_hook_that_defaults_to_none():
    """The identity guarantee, at the signature.

    One `is not None` test per slice — the same test `on_slice` and
    `should_stop` already carry — and the loop is otherwise the loop it was.
    """
    import inspect
    from playing.v6.playv6 import Engine
    sig = inspect.signature(Engine.search_move)
    assert "budget_hook" in sig.parameters
    assert sig.parameters["budget_hook"].default is None
    source = inspect.getsource(Engine.search_move)
    assert "if budget_hook is not None:" in source
    assert "revised = budget_hook(" in source
