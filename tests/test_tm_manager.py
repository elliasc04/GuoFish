def _uci_for_plan(config, root_visits: int = 0, move_stats=None,
                  children=()):
    """A UCIEngine with just enough of itself to answer a planner question.

    `__new__` rather than `__init__`: constructing the real thing builds an
    `Engine`, which imports torch and loads a model. Every attribute the
    planner touches is set here and nothing else is, so a planner that started
    reaching for the evaluator would fail loudly rather than quietly.
    """
    import chess
    module = wrapper()
    uci = module.UCIEngine.__new__(module.UCIEngine)
    uci.config = config
    search = type("_S", (), {"root_visits": root_visits,
                             "root_children": staticmethod(lambda: list(children))})()
    uci.engine = type("_E", (), {"ready": True, "search": search})()
    uci.board = chess.Board()
    uci.move_stats = move_stats
    uci.tm = TimeManager()
    return uci, module


