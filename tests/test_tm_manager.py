def test_part1_each_bucket_starts_at_its_own_fitted_median():
    tm = TimeManager()
    for lo, hi, median in NPS_BUCKETS:
        rate, bucket, seeded = tm.nps_for((lo + hi) // 2)
        assert bucket == (lo, hi)
        assert rate == median
        assert seeded


def test_part1_an_unknown_piece_count_falls_back_to_the_global_median():
    tm = TimeManager()
    rate, bucket, seeded = tm.nps_for(None)
    assert bucket is None and seeded
    assert rate == DEFAULT_CONSTANTS.nps_global


def test_part1_the_smoother_moves_by_alpha_and_only_within_its_bucket():
    tm = TimeManager()
    alpha = DEFAULT_CONSTANTS.nps_alpha
    seed = NPS_BUCKETS[0][2]
    tm.observe(30, delivered=200_000, wall_s=5.0)      # 40,000 sims/s
    got, _bucket, seeded = tm.nps_for(30)
    assert not seeded
    assert got == pytest.approx(alpha * 40_000 + (1 - alpha) * seed, rel=1e-9)
    # The other buckets are untouched: the whole point of bucketing is that an
    # endgame observation does not move the opening estimate.
    assert tm.nps_for(20)[0] == NPS_BUCKETS[1][2]


def test_part1_a_degenerate_search_produces_no_observation():
    """L0's own filter, applied at the source rather than downstream.

    A move ended by `stop` at game end, or by the depth-1 mate short-circuit,
    delivers a handful of simulations in a few milliseconds and its "nps" is a
    division by nothing.
    """
    tm = TimeManager()
    assert tm.observe(30, delivered=12, wall_s=0.004) is None
    assert tm.observe(30, delivered=0, wall_s=9.0) is None
    assert tm.nps_for(30)[2] is True, "still the seed"


def test_part1_new_game_clears_the_smoother():
    """`alpha` was measured within games and never across a boundary (L0 §8)."""
    tm = TimeManager()
    tm.observe(30, delivered=200_000, wall_s=5.0)
    assert not tm.nps_for(30)[2]
    tm.new_game()
    assert tm.nps_for(30)[2]
    assert tm.nps_for(30)[0] == NPS_BUCKETS[0][2]


