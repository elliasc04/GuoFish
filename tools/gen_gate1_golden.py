def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--corpus", choices=("quiet", "terminal"), default="quiet",
                        help="quiet = C5's sampled midgames, rejected on any "
                             "terminal/draw/cap; terminal = C6's hand-specified "
                             "corpus, which exists to hit exactly those")
    parser.add_argument("--pgn", type=Path, default=DEFAULT_PGN)
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--positions", type=int, default=20,
                        help="quiet positions to accept (brief requires >= 20)")
    parser.add_argument("--sims", type=int, default=5000,
                        help="simulations per run (brief requires >= 5000)")
    parser.add_argument("--full-tree-positions", type=int, default=4,
                        help="positions additionally recorded with EVERY node, "
                             "including unvisited children, at --full-tree-sims")
    parser.add_argument("--full-tree-sims", type=int, default=800)
    parser.add_argument("--seed", type=int, default=20260806)
    parser.add_argument("--min-ply", type=int, default=24)
    parser.add_argument("--max-ply", type=int, default=60)
    parser.add_argument("--min-pieces", type=int, default=16)
    parser.add_argument("--max-candidates", type=int, default=400)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--out-dump", type=Path, default=None)
    parser.add_argument("--out-trees", type=Path, default=None)
    parser.add_argument("--out-manifest", type=Path, default=None)
    parser.add_argument("--limit", type=int, default=0,
                        help="terminal corpus only: stop after N specs (smoke runs)")
    parser.add_argument("--only", default="",
                        help="terminal corpus only: comma-separated spec names to "
                             "run. For iterating on one spec; a filtered run is "
                             "not acceptance-grade.")
    parser.add_argument("--max-sims", type=int, default=0,
                        help="terminal corpus only: cap every spec's simulation "
                             "count. For smoke runs; a capped run is not "
                             "acceptance-grade and the manifest records the cap.")
    parser.add_argument("--force", action="store_true",
                        help="overwrite existing golden files")
    parser.add_argument("--smoke", action="store_true",
                        help="skip the determinism self-check (fast iteration only)")
    args = parser.parse_args()

    terminal = args.corpus == "terminal"
    if args.out_dump is None:
        args.out_dump = TERMINAL_DUMP if terminal else DEFAULT_DUMP
    if args.out_trees is None:
        args.out_trees = TERMINAL_TREES if terminal else DEFAULT_TREES
    if args.out_manifest is None:
        args.out_manifest = TERMINAL_MANIFEST if terminal else DEFAULT_MANIFEST

    outputs = [args.out_dump, args.out_trees, args.out_manifest]
    existing = [p for p in outputs if p.exists()]
    if existing and not args.force:
        print("refusing to overwrite existing golden files without --force:",
              file=sys.stderr)
        for p in existing:
            print(f"  {p}", file=sys.stderr)
        return 2

    if terminal:
        if len(TERMINAL_POSITIONS) < 20:
            print(f"ERROR: the terminal corpus has {len(TERMINAL_POSITIONS)} "
                  f"specs; the brief requires >= 20.", file=sys.stderr)
            return 1
    else:
        if args.positions < 20:
            print(f"WARNING: --positions {args.positions} is below the 20 the brief "
                  f"requires; this run is not acceptance-grade.", file=sys.stderr)
        if args.sims < 5000:
            print(f"WARNING: --sims {args.sims} is below the 5000 the brief "
                  f"requires; this run is not acceptance-grade.", file=sys.stderr)

    device = torch.device(args.device)
    model = load_model(args.model, device)

    # THE flag. Everything downstream assumes children are canonically ordered,
    # and walk_tree asserts it per node rather than trusting this line.
    mctsv4.GATE1_CANONICAL_ORDER = True

    recorder = Recorder()
    uninstall = install_hooks(recorder)
    default_max_depth = mctsv4.MAX_TREE_DEPTH
    try:
        if terminal:
            return _run_terminal(args, model, device, recorder)
        return _run(args, model, device, recorder)
    finally:
        uninstall()
        mctsv4.GATE1_CANONICAL_ORDER = False
        mctsv4.MAX_TREE_DEPTH = default_max_depth


def _run(args, model, device, recorder: Recorder) -> int:
    print(f"scanning {args.pgn}")
    candidates = candidate_positions(
        args.pgn, seed=args.seed, min_ply=args.min_ply, max_ply=args.max_ply,
        min_pieces=args.min_pieces, max_candidates=args.max_candidates)
    print(f"{len(candidates)} candidate positions pass the cheap filters")
    if len(candidates) < args.positions:
        print(f"ERROR: only {len(candidates)} candidates for "
              f"{args.positions} positions", file=sys.stderr)
        return 1

    mcts = build_engine(model, device, cache_size=1)

    accepted: list[dict] = []
    rejected: list[dict] = []
    runs: list[dict] = []

    try:
        for white, black, ply, board in candidates:
            if len(accepted) >= args.positions:
                break
            fen = fen_of(board)
            print(f"[{len(accepted) + 1}/{args.positions}] ply {ply}  {fen}",
                  flush=True)

            position_runs = []
            reason = None
            for vl in VIRTUAL_LOSSES:
                mctsv4.VIRTUAL_LOSS = vl
                try:
                    records, audit = run_reference(mcts, board, args.sims,
                                                   recorder, visited_only=True)
                except QuietnessFailure as exc:
                    reason = f"VL={vl}: {exc}"
                    break
                audit.update(virtual_loss=vl, sims=args.sims, full_tree=False)
                position_runs.append({"records": records, "audit": audit})
                print(f"      VL={vl:<4} {audit['nodes_recorded']:>7} visited "
                      f"nodes  depth<={audit['max_depth']:<3} "
                      f"{audit['seconds']:.1f}s  best={audit['best_move']}",
                      flush=True)

            if reason is not None:
                print(f"      rejected: {reason}", flush=True)
                rejected.append({"fen": fen, "ply": ply, "reason": reason})
                continue

            index = len(accepted)
            for run in position_runs:
                run["audit"].update(position=index, fen=fen)
                runs.append(run)
            accepted.append({"index": index, "fen": fen, "ply": ply,
                             "white": white, "black": black})

        if len(accepted) < args.positions:
            print(f"ERROR: accepted only {len(accepted)} of {args.positions} "
                  f"positions; {len(rejected)} rejected", file=sys.stderr)
            return 1

        # --- full-tree control runs -------------------------------------
        # The 5,000-simulation runs above record only the visited subtree: a
        # 5,000-sim tree holds ~175,000 nodes, of which ~5,000 have any visits,
        # and the rest carry visit_count 0 and value_sum 0.0 on both sides by
        # construction. Their PRIORS are not trivial, though -- they come from
        # the dump and their order is the canonical ordering under test -- so a
        # smaller run records every node, unvisited children included, and the
        # test compares that end to end. Without these the whole-tree path would
        # be argued rather than measured.
        full_tree_runs = []
        for spec in accepted[:args.full_tree_positions]:
            board = chess.Board(spec["fen"])
            print(f"[full-tree] position {spec['index']} at "
                  f"{args.full_tree_sims} sims", flush=True)
            for vl in VIRTUAL_LOSSES:
                mctsv4.VIRTUAL_LOSS = vl
                records, audit = run_reference(mcts, board, args.full_tree_sims,
                                               recorder, visited_only=False)
                audit.update(virtual_loss=vl, sims=args.full_tree_sims,
                             full_tree=True, position=spec["index"],
                             fen=spec["fen"])
                full_tree_runs.append({"records": records, "audit": audit})
                print(f"      VL={vl:<4} {audit['nodes_recorded']:>7} nodes "
                      f"(all)  {audit['seconds']:.1f}s", flush=True)
        runs.extend(full_tree_runs)

        # --- determinism self-check -------------------------------------
        # C3b asks for this to be pinned and C5 depends on it: the equivalence
        # configuration must be bit-deterministic across runs, or the golden
        # trees describe one run rather than the reference's behaviour. Re-runs
        # the first position at VL 2.5 and diffs the whole record list.
        determinism = None
        if not args.smoke:
            print("[determinism] re-running position 0 at VL=2.5", flush=True)
            mctsv4.VIRTUAL_LOSS = 2.5
            board = chess.Board(accepted[0]["fen"])
            repeat, _ = run_reference(mcts, board, args.sims, recorder,
                                      visited_only=True)
            original = next(r["records"] for r in runs
                            if r["audit"]["position"] == 0
                            and r["audit"]["virtual_loss"] == 2.5
                            and not r["audit"]["full_tree"])
            identical = (len(repeat) == len(original) and
                         all(a[:3] == b[:3] and a[5] == b[5] and
                             struct.pack("<d", a[3]) == struct.pack("<d", b[3])
                             for a, b in zip(repeat, original)))
            if not identical:
                print("ERROR: the equivalence configuration is NOT "
                      "bit-deterministic across runs; golden trees would be "
                      "unreproducible.", file=sys.stderr)
                return 1
            determinism = {"position": 0, "virtual_loss": 2.5,
                           "nodes": len(repeat), "identical": True}
            print(f"[determinism] identical over {len(repeat)} nodes",
                  flush=True)
    finally:
        mctsv4.VIRTUAL_LOSS = 2.5
        mcts.shutdown()

    # --- write ----------------------------------------------------------
    args.out_dump.parent.mkdir(parents=True, exist_ok=True)
    dump_stats = write_dump(args.out_dump, recorder)
    tree_stats = write_trees(args.out_trees, runs)

    manifest = {
        "provenance": {
            "generator": "tools/gen_gate1_golden.py",
            "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "python": platform.python_version(),
            "python_build": sys.version,
            "platform": platform.platform(),
            "python_chess": chess.__version__,
            "numpy": np.__version__,
            "torch": torch.__version__,
            "device": str(device),
            "cuda_device": (torch.cuda.get_device_name(0)
                            if device.type == "cuda" else None),
            "model": str(args.model.relative_to(REPO_ROOT)),
            "model_sha256": sha256_of(args.model),
            "reference_sha256": sha256_of(REPO_ROOT / "core" / "mctsv4.py"),
            "seed": args.seed,
            "argv": sys.argv[1:],
        },
        "corpus": "quiet",
        "config": {
            "workers": 1,
            "cache_size": 1,
            "tablebase": False,
            "dirichlet": False,
            "canonical_order_patch": True,
            "virtual_losses": list(VIRTUAL_LOSSES),
            "sims": args.sims,
            "full_tree_sims": args.full_tree_sims,
            "max_tree_depth": mctsv4.MAX_TREE_DEPTH,
            "search_params": {
                "c_init": SearchParams().c_init,
                "c_base": SearchParams().c_base,
                "fpu_root": SearchParams().fpu_root,
                "fpu_tree": SearchParams().fpu_tree,
                "policy_temperature": SearchParams().policy_temperature,
            },
        },
        "positions": accepted,
        "rejected": rejected,
        "runs": [r["audit"] for r in runs],
        "dump": dump_stats,
        "trees": tree_stats,
        "determinism_check": determinism,
    }
    with open(args.out_manifest, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")

    print()
    print(f"dump     {args.out_dump}  "
          f"{dump_stats['entries']} positions, {dump_stats['moves']} moves")
    print(f"trees    {args.out_trees}  "
          f"{tree_stats['runs']} runs, {tree_stats['nodes']} nodes")
    print(f"manifest {args.out_manifest}  "
          f"{len(accepted)} positions accepted, {len(rejected)} rejected")
    return 0


