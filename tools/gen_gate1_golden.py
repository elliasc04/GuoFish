def candidate_positions(pgn_path: Path, *, seed: int, min_ply: int, max_ply: int,
                        min_pieces: int, max_candidates: int):
    """Quiet-looking midgame positions, one per game, in a deterministic order.

    Game-realistic rather than constructed: scope 3 says the ~400 benchmark games
    are sufficient for everything needing realistic positions, and constructing
    midgames by hand would bias the corpus toward whatever the author thinks a
    midgame looks like. The filters below only remove positions that are
    obviously unusable; the real acceptance test is the reference run itself.
    """
    rng = np.random.default_rng(seed)
    out = []
    with open(pgn_path, encoding="utf-8", errors="replace") as handle:
        while len(out) < max_candidates:
            game = chess.pgn.read_game(handle)
            if game is None:
                break
            moves = list(game.mainline_moves())
            if len(moves) < max_ply + 8:
                continue
            board = game.board()
            ply_choice = int(rng.integers(min_ply, max_ply + 1))
            ok = True
            for i, move in enumerate(moves):
                if i >= ply_choice:
                    break
                board.push(move)
            else:
                ok = False
            if not ok:
                continue

            if board.is_game_over():
                continue
            if board.is_check():
                # Not because checks are unsupported -- they are ordinary
                # positions -- but because a position in check is materially
                # more likely to have a forced mate inside 5,000 simulations,
                # and every such candidate costs a full reference run to reject.
                continue
            if chess.popcount(board.occupied) < min_pieces:
                continue
            if board.halfmove_clock > 6:
                continue
            if len(list(board.legal_moves)) < 10:
                continue
            history = mctsv4.build_repetition_history(board)
            if max(history.values()) > 1:
                continue
            # Re-derive the position from its own FEN, dropping the move stack.
            #
            # Two things depend on this. `build_repetition_history` walks the
            # stack, so a position carrying one would search against a game
            # history the C++ side (which is handed a FEN) does not have --
            # the run would not be reproducible from what the manifest records.
            # And the FEN is written with en_passant="fen", so the ep square
            # survives a double push with no legal capture; python-chess's
            # DEFAULT fen() omits it, which would move token 66 and therefore
            # the nn_key on ~3% of positions. See DECISIONS.md, C2.
            out.append((game.headers.get("White", "?"),
                        game.headers.get("Black", "?"),
                        ply_choice, chess.Board(fen_of(board))))
    return out


