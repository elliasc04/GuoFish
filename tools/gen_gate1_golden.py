def build_line(base_fen: str, moves: list[str]) -> chess.Board:
    """The root board for one spec: `base_fen` with `moves` legally played onto it.

    Every assertion here is a precondition of the corpus rather than a defensive
    habit. A base FEN that is not `is_valid()`, or a move that is not legal from
    where it is played, would put a position in the corpus that no game can
    reach — and the whole point of building the roots this way instead of writing
    them out is that the ep square of every position after the base is set by
    python-chess's own `push()`, i.e. by the raw rule the C++ side derives.
    """
    board = chess.Board(base_fen)
    if not board.is_valid():
        raise AssertionError(f"base FEN is not a legal position: {base_fen} "
                             f"({board.status()!r})")
    if board.ep_square is not None:
        raise AssertionError(
            f"base FEN {base_fen} names an en-passant square. Hand-written ep "
            f"fields are the one thing the C6 corpus must not contain -- see "
            f"DECISIONS.md, C3, on has_legal_en_passant.")
    for uci in moves:
        move = chess.Move.from_uci(uci)
        if move not in board.legal_moves:
            raise AssertionError(f"{uci} is not legal in {board.fen()} "
                                 f"(spec base {base_fen})")
        board.push(move)
    if board.is_game_over():
        raise AssertionError(f"root position is already over: {board.fen()}")
    if not any(board.legal_moves):
        raise AssertionError(f"root position has no legal moves: {board.fen()}")
    return board


def history_fens(board: chess.Board) -> list[str]:
    """The pre-root game history, as the FENs `build_repetition_history` walks.

    Exactly that function's loop: pop `min(halfmove_clock, plies)` moves and take
    each position on the way, most recent first. The ROOT is not included --
    `build_repetition_history` seeds its counter with the root separately, and so
    does the C++ `set_position`, so including it here would count it twice.

    `fen_of` rather than `Board.fen()`: the default writes the ep square only
    when a capture is legal, which would move token 66 and therefore the nn_key
    on the positions where the two rules differ. See DECISIONS.md, C2.
    """
    out: list[str] = []
    probe = board.copy()
    for _ in range(min(probe.halfmove_clock, len(probe.move_stack))):
        probe.pop()
        out.append(fen_of(probe))
    return out


def _run_terminal(args, model, device, recorder: Recorder) -> int:
    specs = TERMINAL_POSITIONS[:args.limit] if args.limit else TERMINAL_POSITIONS
    if args.only:
        wanted = {name.strip() for name in args.only.split(",") if name.strip()}
        unknown = wanted - {spec[0] for spec in specs}
        if unknown:
            print(f"ERROR: unknown spec name(s): {sorted(unknown)}", file=sys.stderr)
            return 1
        specs = [spec for spec in specs if spec[0] in wanted]
    print(f"terminal corpus: {len(specs)} specs")

    mcts = build_engine(model, device, cache_size=1)
    accepted: list[dict] = []
    runs: list[dict] = []
    default_max_depth = mctsv4.MAX_TREE_DEPTH

    try:
        for index, (name, categories, base_fen, moves, sims, max_depth) in enumerate(specs):
            if args.max_sims:
                sims = min(sims, args.max_sims)
            board = build_line(base_fen, moves)
            fen = fen_of(board)
            history = history_fens(board)
            print(f"[{index + 1}/{len(specs)}] {name:24s} {fen}", flush=True)
            print(f"{'':29s} categories={','.join(categories)} sims={sims} "
                  f"max_depth={max_depth} history={len(history)}", flush=True)

            # The reference reads MAX_TREE_DEPTH as a module global at every
            # descent step, so setting it here is how a depth-cap spec is run.
            # The C++ side reads SearchConfig.max_tree_depth, which the test
            # takes from this run's manifest entry.
            mctsv4.MAX_TREE_DEPTH = max_depth

            position_runs = []
            for vl in VIRTUAL_LOSSES:
                mctsv4.VIRTUAL_LOSS = vl
                records, audit = run_reference(mcts, board, sims, recorder,
                                               visited_only=True, strict=False)
                audit.update(virtual_loss=vl, sims=sims, full_tree=False,
                             position=index, name=name, fen=fen,
                             max_tree_depth=max_depth, categories=list(categories))
                position_runs.append({"records": records, "audit": audit})
                census = audit["census"]
                print(f"      VL={vl:<4} visits={audit['root_visits']:<5} "
                      f"nodes={audit['nodes_recorded']:<6} "
                      f"depth<={audit['max_depth']:<3} "
                      f"term={census['terminal_nodes']:<4} "
                      f"(win {census['terminal_win']}, draw {census['terminal_draw']}) "
                      f"draws={audit['draw_by_rule_hits']:<5} "
                      f"cap={census['at_depth_cap']:<4} "
                      f"early={audit['early_exit']!s:<5} "
                      f"best={audit['best_move']} {audit['seconds']:.1f}s",
                      flush=True)

            for run in position_runs:
                runs.append(run)
            accepted.append({"index": index, "name": name, "fen": fen,
                             "base_fen": base_fen, "moves": list(moves),
                             "history": history, "categories": list(categories),
                             "sims": sims, "max_tree_depth": max_depth})

        # --- full-tree control runs -------------------------------------
        # Same reasoning as the quiet corpus: the visited-subtree runs above say
        # nothing about UNVISITED children, whose priors and order are under
        # test. Four specs are re-run at a smaller budget recording every node.
        # The four are chosen across categories rather than by index, so the
        # control covers a mate, a stalemate, a repetition and a cap.
        full_tree_names = ("mate2-rooks-ladder", "stalemate-queen-h1",
                           "threefold-blocked-pawns", "depthcap-07")
        for spec in accepted:
            if spec["name"] not in full_tree_names:
                continue
            board = build_line(spec["base_fen"], spec["moves"])
            mctsv4.MAX_TREE_DEPTH = spec["max_tree_depth"]
            print(f"[full-tree] {spec['name']} at {args.full_tree_sims} sims", flush=True)
            for vl in VIRTUAL_LOSSES:
                mctsv4.VIRTUAL_LOSS = vl
                records, audit = run_reference(mcts, board, args.full_tree_sims,
                                               recorder, visited_only=False,
                                               strict=False)
                audit.update(virtual_loss=vl, sims=args.full_tree_sims,
                             full_tree=True, position=spec["index"],
                             name=spec["name"], fen=spec["fen"],
                             max_tree_depth=spec["max_tree_depth"],
                             categories=list(spec["categories"]))
                runs.append({"records": records, "audit": audit})
                print(f"      VL={vl:<4} {audit['nodes_recorded']:>7} nodes (all)  "
                      f"{audit['seconds']:.1f}s", flush=True)

        # --- determinism self-check -------------------------------------
        determinism = None
        if not args.smoke:
            # The LARGEST recorded tree, not the first position. The first is a
            # mate-in-one, where the short-circuit stops the reference at two
            # nodes — re-running that and finding it identical says almost
            # nothing. Determinism is a claim about a 5,000-simulation run, so it
            # is checked on one.
            biggest = max(
                (r for r in runs if not r["audit"]["full_tree"]),
                key=lambda r: r["audit"]["nodes_recorded"])
            target = next(spec for spec in accepted
                          if spec["index"] == biggest["audit"]["position"])
            print(f"[determinism] re-running {target['name']} at VL=2.5 "
                  f"({biggest['audit']['nodes_recorded']} nodes)", flush=True)
            mctsv4.MAX_TREE_DEPTH = target["max_tree_depth"]
            mctsv4.VIRTUAL_LOSS = 2.5
            board = build_line(target["base_fen"], target["moves"])
            repeat, _ = run_reference(mcts, board, target["sims"], recorder,
                                      visited_only=True, strict=False)
            original = next(r["records"] for r in runs
                            if r["audit"]["position"] == target["index"]
                            and r["audit"]["virtual_loss"] == 2.5
                            and not r["audit"]["full_tree"])
            identical = (len(repeat) == len(original) and
                         all(a[:3] == b[:3] and a[5:] == b[5:] and
                             struct.pack("<d", a[3]) == struct.pack("<d", b[3])
                             for a, b in zip(repeat, original)))
            if not identical:
                print("ERROR: the equivalence configuration is NOT "
                      "bit-deterministic across runs; golden trees would be "
                      "unreproducible.", file=sys.stderr)
                return 1
            determinism = {"position": target["index"], "virtual_loss": 2.5,
                           "nodes": len(repeat), "identical": True}
            print(f"[determinism] identical over {len(repeat)} nodes", flush=True)
    finally:
        mctsv4.VIRTUAL_LOSS = 2.5
        mctsv4.MAX_TREE_DEPTH = default_max_depth
        mcts.shutdown()

    # --- coverage -------------------------------------------------------
    # Measured, not declared. `categories` on a spec says what it was WRITTEN to
    # exercise; this counts what the reference actually did, and the two are
    # cross-checked here and again in tests/test_c6_gate1_full.py. A spec whose
    # intended class never fired is a spec that is not testing what it claims.
    coverage = {
        "checkmate_terminals": sum(r["audit"]["census"]["terminal_win"] for r in runs),
        "draw_terminals": sum(r["audit"]["census"]["terminal_draw"] for r in runs),
        "draw_by_rule_hits": sum(r["audit"]["draw_by_rule_hits"] for r in runs),
        "depth_cap_nodes": sum(r["audit"]["census"]["at_depth_cap"] for r in runs),
        "early_exits": sum(1 for r in runs if r["audit"]["early_exit"]),
        "terminal_with_children": sum(
            r["audit"]["census"]["terminal_with_children"] for r in runs),
    }
    missing = []
    if coverage["checkmate_terminals"] == 0:
        missing.append("no checkmate terminal in any run")
    if coverage["draw_terminals"] == 0:
        missing.append("no drawn terminal (stalemate / insufficient / rule) in any run")
    if coverage["draw_by_rule_hits"] == 0:
        missing.append("_draw_by_rule never fired (no threefold, no fifty-move)")
    if coverage["depth_cap_nodes"] == 0:
        missing.append("the depth cap never fired")
    if coverage["early_exits"] == 0:
        missing.append("the depth-1 mate short-circuit never fired")
    if missing:
        print("ERROR: the terminal corpus does not exercise what it claims:",
              file=sys.stderr)
        for line in missing:
            print(f"  {line}", file=sys.stderr)
        print("  Refusing to write golden data a test would then certify as "
              "covering C6.", file=sys.stderr)
        return 1

    # --- write ----------------------------------------------------------
    args.out_dump.parent.mkdir(parents=True, exist_ok=True)
    dump_stats = write_dump(args.out_dump, recorder)
    tree_stats = write_trees(args.out_trees, runs)

    manifest = {
        "provenance": {
            "generator": "tools/gen_gate1_golden.py --corpus terminal",
            "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "python": platform.python_version(),
            "python_build": sys.version,
            "platform": platform.platform(),
            "python_chess": chess.__version__,
            "numpy": np.__version__,
            "torch": torch.__version__,
            "device": str(device),
            "cuda_device": (torch.cuda.get_device_name(0)
                            if device.type == "cuda" else None),
            "model": str(args.model.relative_to(REPO_ROOT)),
            "model_sha256": sha256_of(args.model),
            "reference_sha256": sha256_of(REPO_ROOT / "core" / "mctsv4.py"),
            "seed": args.seed,
            "argv": sys.argv[1:],
        },
        "corpus": "terminal",
        "config": {
            "workers": 1,
            "cache_size": 1,
            "tablebase": False,
            "dirichlet": False,
            "canonical_order_patch": True,
            "virtual_losses": list(VIRTUAL_LOSSES),
            "full_tree_sims": args.full_tree_sims,
            # The DEFAULT, i.e. the reference's own constant. Per-run overrides
            # live on each run's `max_tree_depth`, and the depth-cap specs are
            # the only ones that differ from this.
            "max_tree_depth": default_max_depth,
            "search_params": {
                "c_init": SearchParams().c_init,
                "c_base": SearchParams().c_base,
                "fpu_root": SearchParams().fpu_root,
                "fpu_tree": SearchParams().fpu_tree,
                "policy_temperature": SearchParams().policy_temperature,
            },
        },
        "positions": accepted,
        "rejected": [],
        "runs": [r["audit"] for r in runs],
        "coverage": coverage,
        "dump": dump_stats,
        "trees": tree_stats,
        "determinism_check": determinism,
    }
    with open(args.out_manifest, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2)
        handle.write("\n")

    print()
    print(f"dump     {args.out_dump}  "
          f"{dump_stats['entries']} positions, {dump_stats['moves']} moves")
    print(f"trees    {args.out_trees}  "
          f"{tree_stats['runs']} runs, {tree_stats['nodes']} nodes, "
          f"{tree_stats['terminal_nodes']} terminal")
    print(f"manifest {args.out_manifest}  {len(accepted)} positions")
    print(f"coverage {coverage}")
    return 0


