def run_reference(mcts: ParallelMCTS, board: chess.Board, sims: int,
                  recorder: Recorder, *, visited_only: bool, strict: bool = True):
    """One reference search, audited. Returns (records, audit) or raises.

    `strict` is the corpus distinction; see walk_tree. In the strict case every
    audit below is a rejection criterion, so a returned audit means the position
    touched nothing C5 excludes. In the non-strict case the same facts are
    recorded into the audit and the position is kept.
    """
    mcts.reset()
    mcts.clear_cache()

    with DrawRuleCounter() as draws:
        started = time.perf_counter()
        best = mcts.search(board.copy(), num_simulations=sims)
        elapsed = time.perf_counter() - started

    if best is None:
        # Only a root with no legal moves produces this, and neither corpus
        # contains one: a finished game has no move to search for.
        raise QuietnessFailure("search returned no move")
    if strict and draws.hits:
        raise QuietnessFailure(f"_draw_by_rule fired {draws.hits} times")

    root = mcts.root
    records, max_depth, expanded, census = walk_tree(
        root, board, recorder, visited_only=visited_only, strict=strict)
    early_exit = int(root.visit_count) != sims
    if strict and early_exit:
        raise QuietnessFailure(
            f"root visit_count {root.visit_count} != requested {sims}; the "
            f"search exited early")

    audit = {
        "best_move": best.uci(),
        "root_visits": int(root.visit_count),
        "nodes_recorded": len(records),
        "expanded_nodes": expanded,
        "max_depth": max_depth,
        "draw_by_rule_hits": draws.hits,
        "seconds": round(elapsed, 3),
        # C6. `early_exit` is the depth-1 mate short-circuit's fingerprint: the
        # reference stopped before reaching `sims` because a worker set
        # completion_event. Recording it is what lets the acceptance test require
        # the SAME truncation from C++, rather than quietly accepting whichever
        # tree it was handed.
        "early_exit": early_exit,
        "census": census,
    }
    return records, audit


def build_engine(model, device, cache_size: int) -> ParallelMCTS:
    return ParallelMCTS(
        model=model,
        device=device,
        num_workers=1,
        cache_size=cache_size,
        tablebase=None,
        params=SearchParams(),
    )


