def nn_key_from_tokens(tokens: torch.Tensor) -> int:
    """`nn_key` over a token tensor, i.e. over the exact bytes the network saw.

    The evaluator is intercepted at the point where it holds `EvalRequest.tokens`,
    which is what `board_to_tokens` produced for that leaf. Hashing the tensor
    rather than re-deriving a board removes any chance that the value recorded
    for a key was computed for a different position -- the same one-source
    discipline scope 2.5 imposes on the C++ cache.
    """
    arr = np.asarray(tokens.detach().to("cpu")).astype("<i4")
    assert arr.shape == (mctsv4.SEQ_LENGTH,), f"tokenizer returned {arr.shape}"
    return fnv1a64(NN_TAG + arr.tobytes())


