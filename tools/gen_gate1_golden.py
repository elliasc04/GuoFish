def write_dump(path: Path, recorder: Recorder) -> dict:
    # Sorted by (nn_key, is_root) so the file has one canonical byte image for a
    # given session and a diff between two generations is readable.
    slots = sorted(recorder.entries)
    missing = [k for k, _ in slots if k not in recorder.values]
    if missing:
        raise AssertionError(
            f"{len(missing)} expanded positions have no recorded network value "
            f"(first {missing[0]:#018x}). The evaluator interception and the "
            f"tree walk disagree about nn_key.")

    move_offset = np.zeros(len(slots) + 1, dtype=np.uint64)
    moves: list[int] = []
    priors32: list[np.float32] = []
    for i, slot in enumerate(slots):
        key = slot[0]
        entry_moves, entry_priors = recorder.entries[slot]
        for packed, prior in zip(entry_moves, entry_priors):
            moves.append(packed)
            narrow = np.float32(prior)
            # The priors are already float32 -- expand() softmaxes a float32
            # tensor and .tolist() promotes exactly -- so narrowing is lossless.
            # Asserted per value rather than argued, because if it ever stopped
            # being true the golden file would silently lose the low bits that
            # Gate 1 is comparing.
            if float(narrow) != prior:
                raise AssertionError(
                    f"prior {prior!r} for nn_key {key:#018x} is not exactly "
                    f"representable as float32")
            priors32.append(narrow)
        move_offset[i + 1] = len(moves)

    np.savez_compressed(
        path,
        keys=np.array([k for k, _ in slots], dtype=np.uint64),
        is_root=np.array([1 if r else 0 for _, r in slots], dtype=np.uint8),
        move_offset=move_offset,
        moves=np.array(moves, dtype=np.uint16),
        priors=np.array(priors32, dtype=np.float32),
        values=np.array([recorder.values[k] for k, _ in slots], dtype=np.float64),
    )
    return {"entries": len(slots),
            "root_entries": sum(1 for _, r in slots if r),
            "moves": len(moves)}


def write_trees(path: Path, runs: list[dict]) -> dict:
    run_offset = np.zeros(len(runs) + 1, dtype=np.uint64)
    depth: list[int] = []
    move: list[int] = []
    visits: list[int] = []
    value_sum: list[float] = []
    prior: list[np.float32] = []
    children: list[int] = []
    terminal: list[int] = []
    terminal_value: list[np.float32] = []

    for i, run in enumerate(runs):
        for d, m, v, vs, p, c, t, tv in run["records"]:
            depth.append(d)
            move.append(m)
            visits.append(v)
            value_sum.append(vs)
            narrow = np.float32(p)
            if float(narrow) != p:
                raise AssertionError(f"prior {p!r} is not exactly float32")
            prior.append(narrow)
            children.append(c)
            terminal.append(t)
            # 1.0, 0.0 and -1.0 are the only values the reference ever writes,
            # and all three are exact in float32. Asserted rather than assumed,
            # for the same reason the priors are.
            narrow_tv = np.float32(tv)
            if float(narrow_tv) != tv:
                raise AssertionError(f"terminal_value {tv!r} is not exactly float32")
            terminal_value.append(narrow_tv)
        run_offset[i + 1] = len(depth)

    np.savez_compressed(
        path,
        run_offset=run_offset,
        depth=np.array(depth, dtype=np.uint16),
        move=np.array(move, dtype=np.uint16),
        visits=np.array(visits, dtype=np.int32),
        value_sum=np.array(value_sum, dtype=np.float64),
        prior=np.array(prior, dtype=np.float32),
        children=np.array(children, dtype=np.uint16),
        terminal=np.array(terminal, dtype=np.uint8),
        terminal_value=np.array(terminal_value, dtype=np.float32),
    )
    return {"runs": len(runs), "nodes": len(depth),
            "terminal_nodes": int(sum(terminal))}


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


