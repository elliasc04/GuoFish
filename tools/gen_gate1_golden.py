class QuietnessFailure(Exception):
    """A candidate position touched machinery C5 does not implement."""


def walk_tree(root: MCTSNode, root_board: chess.Board, recorder: Recorder,
              *, visited_only: bool, strict: bool = True):
    """Canonical DFS preorder over the tree, collecting records and dump entries.

    Iterative rather than recursive: MAX_TREE_DEPTH is 80 so recursion would in
    fact be safe, but the audit below has to be able to *report* a depth
    violation rather than hit a RecursionError on the way to it.

    `strict` selects between the two corpora's audits, and the difference is the
    whole distinction between them. With strict=True (C5) the walk RAISES
    QuietnessFailure at the first sign of the terminal, draw or depth-cap
    machinery, so the position is rejected. With strict=False (C6) it COUNTS the
    same signs into `census` and keeps going, so the manifest can state what the
    corpus exercised.
    """
    records: list[tuple[int, int, int, float, float, int, int, float]] = []
    board = root_board.copy(stack=False)
    max_depth = 0
    expanded_nodes = 0
    census = {
        "terminal_nodes": 0,
        "terminal_win": 0,       # terminal_value == 1.0 -- checkmate, mover won
        "terminal_draw": 0,      # terminal_value == 0.0 -- stalemate/draw/rule
        "terminal_loss": 0,      # terminal_value == -1.0; unreachable, counted anyway
        "unexpanded_visited": 0,  # the depth-cap signature, or a claimable draw
        "terminal_with_children": 0,  # THE bestmove-0000 STATE. Must stay 0.
        "at_depth_cap": 0,
    }

    # (node, depth, packed move that reached it, iterator over children, pushed?)
    # A hand-rolled stack of frames; `pending` is the reversed child list so
    # pop() yields canonical order.
    stack: list[tuple[MCTSNode, int, int, list]] = []

    def visit(node: MCTSNode, depth: int, packed: int) -> None:
        nonlocal max_depth, expanded_nodes
        if depth > max_depth:
            max_depth = depth

        if node.visit_count > 0:
            if node.is_terminal:
                if strict:
                    raise QuietnessFailure(
                        f"node at depth {depth} is terminal (value "
                        f"{node.terminal_value}) -- checkmate, stalemate, "
                        f"repetition or fifty-move is in range")
                census["terminal_nodes"] += 1
                if node.terminal_value == 1.0:
                    census["terminal_win"] += 1
                elif node.terminal_value == 0.0:
                    census["terminal_draw"] += 1
                else:
                    census["terminal_loss"] += 1
                if node.children:
                    # The reference CAN reach this: the is_game_over path sets
                    # is_expanded on a node whose children dict is empty, and a
                    # later _expand_root on the same node would fill it. It
                    # cannot happen inside one search, and the C++ arena cannot
                    # represent it at all -- so a non-zero count here would mean
                    # the reference had done something C++ is structurally
                    # unable to copy, which is worth knowing loudly.
                    census["terminal_with_children"] += 1
            elif not node.is_expanded or not node.children:
                if strict:
                    raise QuietnessFailure(
                        f"node at depth {depth} has {node.visit_count} visits but "
                        f"is not expanded -- this is the depth-cap signature")
                census["unexpanded_visited"] += 1
            # Gated on visit_count because an UNVISITED child at depth 80 is
            # merely a node the search never entered, whereas a visited one at
            # that depth is the cap having fired. Only the second is a reason to
            # reject the position.
            if depth >= mctsv4.MAX_TREE_DEPTH:
                if strict:
                    raise QuietnessFailure(
                        f"tree reached depth {depth} >= MAX_TREE_DEPTH "
                        f"({mctsv4.MAX_TREE_DEPTH}) with visits")
                census["at_depth_cap"] += 1

        records.append((depth, packed, node.visit_count, node.value_sum,
                        node.prior, len(node.children),
                        1 if node.is_terminal else 0, node.terminal_value))

        if node.children:
            expanded_nodes += 1
            moves = tuple(pack_move(m) for m in node.children)
            priors = tuple(c.prior for c in node.children.values())
            # The order the search actually holds them in must already be
            # canonical; the flag patch is what guarantees it. Checking rather
            # than sorting here is deliberate -- sorting would paper over a
            # patch that failed to apply, and the whole dump would then be
            # ordered differently from the tree it came from.
            keys = [canonical_key(m) for m in moves]
            if keys != sorted(keys):
                raise AssertionError(
                    "children are not in canonical order; is "
                    "mctsv4.GATE1_CANONICAL_ORDER set?")
            recorder.record_entry(nn_key_of_board(board), depth == 0, moves,
                                  priors)

    def children_frames(node: MCTSNode) -> list:
        out = []
        for move, child in node.children.items():
            if visited_only and child.visit_count == 0:
                continue
            out.append((move, child))
        out.reverse()
        return out

    def nn_key_of_board(b: chess.Board) -> int:
        return py_nn_key(b)

    visit(root, 0, 0)
    stack.append((root, 0, 0, children_frames(root)))

    while stack:
        node, depth, packed, pending = stack[-1]
        if not pending:
            stack.pop()
            if stack:
                board.pop()
            continue
        move, child = pending.pop()
        board.push(move)
        visit(child, depth + 1, pack_move(move))
        child_pending = children_frames(child)
        if child_pending:
            stack.append((child, depth + 1, pack_move(move), child_pending))
        else:
            board.pop()

    return records, max_depth, expanded_nodes, census


