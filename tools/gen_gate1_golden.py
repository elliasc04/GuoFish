def pack_move(move: chess.Move) -> int:
    """(from, to, promotion) packed into the uint16 the C++ arena stores.

    from << 10 | to << 4 | promo, squares numbered rank*8 + file (python-chess's
    numbering, which is also chess-library's). The promotion codes are
    ALPHABETICAL by UCI letter -- b=1, n=2, q=3, r=4, none=0 -- not by piece
    value, so that sorting on the derived canonical key reproduces byte order on
    the UCI string. See cpp/arena.hpp.

    python-chess's generators already emit standard (non-Chess960) castling
    moves, so `move.to_square` is the king's destination (g1/c1), not the rook's.
    That is the normalised destination C1 established and the one the C++ side
    sorts on.
    """
    promo = PROMO_CODE[move.promotion]
    return (move.from_square << 10) | (move.to_square << 4) | promo


def canonical_key(packed: int) -> int:
    """Sort key whose integer order is byte order on the move's UCI string.

    Square indices are rank-major (a1, b1, ... h1, a2) while UCI string order is
    file-major (a1, a2, ... a8, b1), so sorting packed moves directly is NOT
    canonical order. Mirrors guofish::canonical_move_key.
    """
    frm = (packed >> 10) & 0x3F
    to = (packed >> 4) & 0x3F
    promo = packed & 0x0F
    return (((frm & 7) << 13) | ((frm >> 3) << 10) | ((to & 7) << 7) |
            ((to >> 3) << 4) | promo)


