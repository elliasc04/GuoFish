"""Generate the Gate 1 golden data — the replay dump and reference trees.

`python-chess` plus `core.mctsv4` plus the v5 checkpoint are the *reference
implementation* (Global Rule 2). The C++ search is judged against these files;
these files are never regenerated to agree with C++. Nothing here imports
`guofish_core`, and the `nn_key` used to index the dump is computed by the pure
Python FNV-1a in tools/gen_key_golden.py, not by the implementation under test.

Usage:
    python tools/gen_gate1_golden.py                        # C5's quiet corpus
    python tools/gen_gate1_golden.py --corpus terminal      # C6's terminal corpus
    python tools/gen_gate1_golden.py --positions 2 --sims 200 --smoke
    python tools/gen_gate1_golden.py --force                # overwrite existing

TWO CORPORA, TWO SETS OF FILES
-------------------------------------------------------------------------------
`--corpus quiet` (the default) is C5's: game-realistic midgame positions sampled
from the benchmark PGNs and *rejected* if the reference search touches a
terminal, draw or depth-cap path. It writes golden/gate1_{dump,trees,manifest}.

`--corpus terminal` is C6's: a hand-specified corpus that exists to touch exactly
that machinery — forced mates in range, stalemate traps, threefold repetitions,
positions at halfmove clock >= 90, insufficient material, and lines that hit the
depth cap. It writes golden/gate1_terminal_{dump,trees,manifest} and never
touches the quiet files, so C5's acceptance data is not regenerated by a C6 run
(Global Rules 1 and 2).

The two differ in one more way that matters. The quiet generator AUDITS AND
REJECTS: a candidate whose tree shows a terminal is discarded. The terminal
generator AUDITS AND RECORDS: every terminal, draw, cap hit and early exit is
counted into the manifest, and the acceptance test asserts the corpus covers each
class. "This corpus exercises stalemate" is then a number in a file rather than a
sentence in a commit message.

-------------------------------------------------------------------------------
What Gate 1 is, and what the replay evaluator is for
-------------------------------------------------------------------------------
Gate 1 asks one question: does the C++ traverse loop -- PUCT selection,
expansion, virtual-loss bookkeeping, backup -- do bit-for-bit what the Python
one does? It deliberately does NOT ask whether C++ can reproduce ATen's softmax,
because it cannot: ATen's CPU path uses a vectorised exp (SLEEF/AVX), not
libm's, so a hand-rolled C++ softmax differs in the last ulp and the divergence
compounds through selection.

So the network is taken out of the loop. Python runs once, with the real
checkpoint, and dumps

    nn_key -> (legal moves in canonical order, priors in canonical order, value)

for every position it expanded. C++ replays that dump as its evaluator. The NN
side is then identical *by construction*, and any divergence is provably in
selection, backup, virtual loss or ordering -- the only thing this gate was ever
meant to test.

The dump is also a test in its own right, and the strongest one in the chunk.
C++ reaches positions by `makeMove` from the root, tokenizes the resulting
search state, and hashes those tokens into an `nn_key`. If its in-search
tokenization derives so much as a different en-passant square, the key it
computes is not a key this file contains, and the lookup misses. A miss is a
hard, named failure on the C++ side -- never a default value -- so the replay
lookup audits in-search tokenization for free.

-------------------------------------------------------------------------------
The equivalence configuration, and why each knob is set the way it is
-------------------------------------------------------------------------------
    1 worker            the gate is about tree logic, not concurrency.
    cache_size=1        NOT cache-off. `cache_size=0` raises IndexError
                        (mctsv4.py TranspositionCache.put indexes a zero-length
                        ring) and no cache-off flag exists. With the tablebase
                        off the cache is result-invariant -- it stores raw
                        logits, and expand() softmaxes them identically whether
                        they arrived from the network or the ring -- so a
                        one-slot ring is a valid neutralisation rather than a
                        workaround. It is cleared before every run here anyway.
    tablebase off       a tablebase value would replace the network's, and the
                        dump would then be recording a value C++ has no way to
                        derive. Out of scope until C7.
    Dirichlet off       noise is random; there is nothing to reproduce.
    GATE1_CANONICAL_ORDER=True
                        see core/mctsv4.py. Children are permuted into canonical
                        (from, to, promotion) order AFTER the softmax, never by
                        sorting the move list before it.

VIRTUAL_LOSS is swept over two values and both are written:

    0.0   the isolation setting. Virtual loss contributes nothing to selection,
          so a failure here is not a virtual-loss failure.
    2.5   the production magnitude, and the semantically representative run.
          `select_child` reads the parent's `effective_visits`, and the parent
          always carries one applied virtual loss mid-descent, so even at one
          worker `parent_visits = N + 1*VL`. Single-threaded Python is still
          deterministic at 2.5, so this must also be bit-exact -- and it is the
          only place virtual loss's apply/repay ordering is exercised before
          concurrency lands in C9.

-------------------------------------------------------------------------------
"Quiet" is a measured property, not an assumption
-------------------------------------------------------------------------------
C5 excludes terminal handling: no checkmate, no stalemate, no repetition, no
fifty-move, no depth cap. That is only safe if the corpus genuinely contains
none of those *within search range*, which is not something position selection
can promise -- a quiet-looking middlegame can still hold a mate in 6 that 5,000
simulations will find.

So every candidate is run first and audited afterwards, and only positions whose
reference run touched none of the excluded machinery are kept. The audit walks
the finished tree and requires, for every node with visit_count > 0:

    is_terminal is False        no checkmate/stalemate/repetition/fifty-move
    is_expanded and children    a visited node that is neither expanded nor
                                terminal is precisely the depth-cap signature
    depth < MAX_TREE_DEPTH      belt and braces on the same thing

plus a direct counter on `_draw_by_rule` returning True. A candidate failing any
of these is discarded with its reason recorded in the manifest, so the rejects
are auditable rather than invisible.

-------------------------------------------------------------------------------
Output
-------------------------------------------------------------------------------
`golden/gate1_dump.npz` -- the replay evaluator dump, CSR-packed:

    keys          uint64[E]    nn_key, ascending, unique
    move_offset   uint64[E+1]  CSR row starts into moves/priors
    moves         uint16[M]    packed (from << 10 | to << 4 | promo), canonical
                               order, over the NORMALISED UCI destination
    priors        float32[M]   post-softmax priors, already permuted into that
                               same canonical order -- C++ reads them directly
                               and performs no softmax in this chunk
    values        float64[E]   the network's ABSOLUTE (White-POV) value

    Priors are float32 because that is what they already are: expand() softmaxes
    a float32 tensor, so every prior is the exact double promotion of a float32
    and storing the narrower type is lossless. Asserted per value, not assumed.

`golden/gate1_trees.npz` -- the reference tree serialisations, CSR-packed by run:

    run_offset    uint64[R+1]  CSR row starts into the per-node arrays
    depth         uint16[T]    plies from the root; the root is 0
    move          uint16[T]    packed move that reaches this node; 0 at the root
    visits        int32[T]
    value_sum     float64[T]   bit-exact; this is the accumulator being compared
    prior         float32[T]
    children      uint16[T]    number of children the node has
    terminal      uint8[T]     node.is_terminal
    terminal_value float32[T]  node.terminal_value

    Nodes are in canonical DFS preorder. The 5,000-simulation runs record the
    VISITED subtree (visit_count > 0); the separate full-tree control runs record
    every node including unvisited children. See --full-tree-sims below for why
    both exist.

    `terminal` / `terminal_value` are C6's and are written by both corpora; the
    quiet files predate them and simply do not carry the columns, which the C6
    test reads as "all zero" — a claim it then asserts against the C++ side
    rather than assuming.

`golden/gate1_manifest.json` -- provenance (interpreter, library versions, model
SHA-256, seed, arguments), the position list, the per-run configuration and the
quietness audit counters. Human-readable; the npz files are not.
"""

