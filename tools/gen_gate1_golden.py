class Recorder:
    """Collects the replay dump across every run of the session.

    `values` is filled by intercepting the evaluator, `entries` by walking each
    finished tree. They are joined on nn_key and cross-checked: a key present in
    one and not the other means the tokenization the evaluator saw and the one
    the walk derives disagree, which would silently corrupt the dump.
    """

    def __init__(self):
        self.values: dict[int, float] = {}
        # Keyed by (nn_key, is_root) -- NOT by nn_key alone. See record_entry.
        self.entries: dict[tuple[int, bool],
                           tuple[tuple[int, ...], tuple[float, ...]]] = {}
        self.value_conflicts = 0
        self.entry_conflicts = 0

    def record_value(self, key: int, value: float) -> None:
        previous = self.values.get(key)
        if previous is None:
            self.values[key] = value
            return
        # Two evaluations of one position must agree bit-for-bit: the model is
        # deterministic and every batch is size 1 at one worker. A conflict here
        # means the run is not reproducible and the dump would be ambiguous, so
        # it aborts rather than picking a winner.
        if struct.pack("<d", previous) != struct.pack("<d", value):
            self.value_conflicts += 1
            raise AssertionError(
                f"nn_key {key:#018x} evaluated twice with different values: "
                f"{previous!r} then {value!r}. The reference run is not "
                f"deterministic; the dump cannot be written.")

    def record_entry(self, key: int, is_root: bool, moves: tuple[int, ...],
                     priors: tuple[float, ...]) -> None:
        """Record one expansion's canonical children.

        THE `is_root` FLAG IS NOT BOOKKEEPING. The reference softmaxes root
        priors and interior priors on DIFFERENT DEVICES, and the two disagree:

          _expand_root  runs its own forward and passes `policy_logits[0]`
                        straight to expand() while it is still a CUDA tensor, so
                        the gather, the .float() and the torch.softmax all run
                        on the GPU.
          interior      BatchedEvaluator._evaluate_batch does a bulk .cpu()
                        before distributing, so expand() softmaxes on the CPU.

        Measured on this checkpoint and a middlegame position: 6 of 37 priors
        differ, max absolute delta 1.9e-9. That is far above the bit level Gate 1
        compares at, and it is load-bearing rather than cosmetic -- priors feed
        PUCT, so the difference propagates into visit counts.

        It only becomes visible when the root position RECURS as an interior
        node, which a middlegame reaches easily in four plies, and it did so on
        the first candidate position at 200 simulations. A dump keyed by nn_key
        alone cannot represent both, so the key is the pair.

        This is a preserved property of the reference, not a defect to fix here.
        Making _expand_root softmax on the CPU would remove it, but that is a
        change to search behaviour beyond the canonical-ordering patch the brief
        sanctions, and Gate 1 exists to reproduce the reference as it is. Flagged
        in DECISIONS.md; a candidate for C10's list, not for this chunk.
        """
        slot = (key, is_root)
        previous = self.entries.get(slot)
        if previous is None:
            self.entries[slot] = (moves, priors)
            return
        old_moves, old_priors = previous
        same = (old_moves == moves and
                all(struct.pack("<d", a) == struct.pack("<d", b)
                    for a, b in zip(old_priors, priors)))
        if not same:
            self.entry_conflicts += 1
            deltas = [abs(a - b) for a, b in zip(old_priors, priors)]
            raise AssertionError(
                f"nn_key {key:#018x} (is_root={is_root}) expanded twice with "
                f"different children: moves equal={old_moves == moves}, "
                f"max prior delta "
                f"{max(deltas) if deltas else float('nan'):.3e}")


def install_hooks(recorder: Recorder):
    """Intercept the three places a network value enters the search.

    Returns an uninstall callable. The hooks only observe -- each calls through
    to the original and reads what it produced -- so the search they wrap is the
    search the reference performs, not a variant of it.
    """
    orig_batch = BatchedEvaluator._evaluate_batch
    orig_inline = BatchedEvaluator.eval_inline
    orig_expand_root = ParallelMCTS._expand_root

    def patched_batch(self, batch):
        orig_batch(self, batch)
        for request in batch:
            if request.value is not None:
                recorder.record_value(nn_key_from_tokens(request.tokens), request.value)

    def patched_inline(self, tokens):
        policy, value = orig_inline(self, tokens)
        recorder.record_value(nn_key_from_tokens(tokens), value)
        return policy, value

    def patched_expand_root(self, root, board):
        orig_expand_root(self, root, board)
        # _expand_root runs its own unbatched forward and writes the result
        # straight into root.value_sum, already converted to the mover's
        # perspective. The conversion is a negation, so it inverts exactly.
        nn_value = root.value_sum if board.turn == chess.BLACK else -root.value_sum
        recorder.record_value(py_nn_key(board), nn_value)

    BatchedEvaluator._evaluate_batch = patched_batch
    BatchedEvaluator.eval_inline = patched_inline
    ParallelMCTS._expand_root = patched_expand_root

    def uninstall():
        BatchedEvaluator._evaluate_batch = orig_batch
        BatchedEvaluator.eval_inline = orig_inline
        ParallelMCTS._expand_root = orig_expand_root

    return uninstall


class DrawRuleCounter:
    """Counts `_draw_by_rule` returning True during a run.

    The tree audit below would catch a repetition or fifty-move draw anyway (it
    leaves a node marked terminal), but this counts the event at its source, so a
    manifest entry of 0 is a direct statement rather than an inference.
    """

    def __init__(self):
        self.hits = 0
        self._orig = mctsv4.MCTSWorker._draw_by_rule

    def __enter__(self):
        counter = self

        def patched(worker_self, board, path_counts):
            result = counter._orig(worker_self, board, path_counts)
            if result:
                counter.hits += 1
            return result

        mctsv4.MCTSWorker._draw_by_rule = patched
        return self

    def __exit__(self, *exc):
        mctsv4.MCTSWorker._draw_by_rule = self._orig
        return False


